// Refresh with: node --import tsx scripts/build-connect-index.mjs (after any catalog change)
// Writes server/connect-index.ts: what the gateway knows about apps that are not connected yet,
// so orbytlink__connect_app can send people to the right form with the right steps.
import fs from "node:fs";
import { catalog } from "../src/catalog.ts";
import { apiPresets } from "../src/api-presets.ts";
import { moreApps } from "../src/catalog-more.ts";
const mcp = catalog
  .filter((p) => !p.hidden)
  .map((p) => ({ kind: "mcp", id: p.id, name: p.name, segment: p.segment, description: p.description, endpoint: p.endpoint, auth: p.auth, ownClient: !!p.ownClient, notes: p.notes, docs: p.docs }));
const api = apiPresets.map((p) => ({ kind: "api", id: p.id, name: p.name, segment: p.category, description: p.description, endpoint: p.baseUrl, auth: p.auth, notes: [p.keyHint, ...(p.note ? [p.note] : [])], docs: p.docsUrl }));
const soon = moreApps.map((a) => ({ kind: "soon", id: a.id, name: a.name, segment: a.segment }));
fs.writeFileSync(
  "server/connect-index.ts",
  `// Generated by scripts/build-connect-index.mjs from the console's catalog; do not edit by hand.\nexport type ConnectEntry = { kind: "mcp" | "api" | "soon"; id: string; name: string; segment: string; description?: string; endpoint?: string; auth?: string; ownClient?: boolean; notes?: string[]; docs?: string };\nexport const connectIndex: ConnectEntry[] = ${JSON.stringify([...mcp, ...api, ...soon])};\n`,
);
console.log(`${mcp.length} MCP servers, ${api.length} APIs, ${soon.length} coming soon`);
