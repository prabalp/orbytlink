const raw = (s, path) => `https://raw.githubusercontent.com/${s.repo}/${s.commit}/${s.base}/${path}`;
async function get(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.text();
}
// The YAML front matter's name and description (single-line or folded `>` blocks).
function frontMatter(md) {
  const m = /^---\n([\s\S]*?)\n---\n?/.exec(md);
  if (!m) throw new Error("SKILL.md has no front matter");
  const out = {};
  const lines = m[1].split("\n");
  for (let i = 0; i < lines.length; i++) {
    const kv = /^([a-z-]+):\s*(.*)$/.exec(lines[i]);
    if (!kv) continue;
    let value = kv[2].trim();
    if (value === ">" || value === "|" || value === ">-" || value === "|-") {
      const block = [];
      while (i + 1 < lines.length && /^\s+/.test(lines[i + 1])) block.push(lines[++i].trim());
      value = block.join(" ");
    }
    out[kv[1]] = value.replace(/^["']|["']$/g, "");
  }
  return { meta: out, body: md.slice(m[0].length).trim() };
}

const skills = [];
for (const [sourceId, path, extras] of SKILLS) {
  const s = SOURCES[sourceId];
  const { meta, body } = frontMatter(await get(raw(s, `${path}/SKILL.md`)));
  const files = [];
  for (const f of extras) files.push({ path: f, content: (await get(raw(s, `${path}/${f}`))).trim() });
  skills.push({
    id: meta.name,
    name: meta.name,
    description: meta.description,
    source: { repo: s.repo, path: `${s.base}/${path}`, commit: s.commit, license: s.license },
    body,
    files,
  });
  console.log(`${meta.name}: ${body.length} chars + ${files.length} files`);
}
writeFileSync(
  new URL("../server/skills-data.ts", import.meta.url),
  `// Generated by scripts/vendor-skills.mjs from pinned upstream commits. Do not edit by hand.\n` +
    `// Licences: anthropics/skills (Apache-2.0, per skill), mattpocock/skills (MIT).\n` +
    `export type VendoredSkill = { id: string; name: string; description: string; source: { repo: string; path: string; commit: string; license: string }; body: string; files: { path: string; content: string }[] };\n` +
    `export const vendoredSkills: VendoredSkill[] = ${JSON.stringify(skills, null, 2)};\n`,
);
