// Refresh with: node scripts/build-app-models.mjs (after scripts/build-model-catalog.py)
// Writes server/model-seed.ts: the starting rows of the model catalog database. The server copies them
// into its database on start (server/models.ts) and serves the catalog from there; operators then add,
// price and route models with `npm run account -- models …`, which the seed never overwrites.
import fs from "node:fs";
const w = {};
new Function("window", fs.readFileSync("landing/model-data.js", "utf8"))(w);
const { updatedAt, models } = w.orbytModels;
// Bump when the rows change shape, so servers refresh the rows the seed owns.
const SEED_VERSION = 2;
// The snapshot's amounts include the 5% markup it was built with; the database keeps cost prices and
// applies AI_MARKUP_PERCENT live.
const cost = (r) => (r ? Math.round((Number(r.amount) / 1.05) * 1e6) / 1e6 : null);
const rows = models.map((m) => ({
  id: m.id,
  name: m.name,
  provider: m.provider,
  // AI Gateway renamed "evaluation" models to decision models: they pick among given options.
  category: m.type === "evaluation" ? "Decision" : m.category,
  context: m.context || null,
  input: cost(m.inputRate),
  inputUnit: m.inputRate?.unit || null,
  output: cost(m.outputRate),
  outputUnit: m.outputRate?.unit || null,
  ...(m.variable ? { from: true } : {}),
  // Callable through OrbytLink today: text models priced per 1M input and output tokens.
  ...(m.type === "language" && m.inputRate?.unit === "1M tokens" && m.outputRate?.unit === "1M tokens" ? { callable: true } : {}),
  // Decision models answer choice, yes/no and score questions (POST /decisions), billed per token.
  ...(m.type === "evaluation" && m.inputRate?.unit === "1M tokens" ? { decision: true } : {}),
}));
fs.writeFileSync(
  "server/model-seed.ts",
  `// Generated by scripts/build-app-models.mjs from the ${updatedAt} model snapshot. Prices are USD at cost\n// (no markup) per unit; the database built from this is what the console and the charges use.\nexport type SeedModel = { id: string; name: string; provider: string; category: string; context: number | null; input: number | null; inputUnit: string | null; output: number | null; outputUnit: string | null; from?: boolean; callable?: boolean; decision?: boolean };\nexport const SEED_AS_OF = "${updatedAt}";\nexport const SEED_VERSION = "${updatedAt}#${SEED_VERSION}";\nexport const seedModels: SeedModel[] = ${JSON.stringify(rows)};\n`,
);
console.log(`${rows.length} models, ${rows.filter((r) => r.callable).length} text, ${rows.filter((r) => r.decision).length} decision`);
