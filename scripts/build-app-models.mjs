// Refresh with: node scripts/build-app-models.mjs (after scripts/build-model-catalog.py)
// Writes src/model-catalog.json, the compact model list the console's Catalog shows. The console
// loads it only when the AI models view opens, so it costs nothing on other pages.
import fs from "node:fs";
const w = {};
new Function("window", fs.readFileSync("landing/model-data.js", "utf8"))(w);
const { updatedAt, models } = w.orbytModels;
const rate = (r) => (r ? [r.amount.replace(/(\.\d*?[1-9])0+$|\.0+$/, "$1"), r.unit] : null);
const out = models.map((m) => ({
  id: m.id,
  name: m.name,
  provider: m.provider,
  category: m.category,
  context: m.context || null,
  input: rate(m.inputRate),
  output: rate(m.outputRate),
  ...(m.variable ? { from: true } : {}),
}));
fs.writeFileSync("src/model-catalog.json", JSON.stringify({ updatedAt, models: out }));
// The server charges from the same prices: text models priced per 1M input and output tokens.
// The amounts already include OrbytLink's 5% markup, and 1 USD per 1M tokens is 1 micro-USD per token.
const charged = Object.fromEntries(
  models
    .filter((m) => m.type === "language" && m.inputRate?.unit === "1M tokens" && m.outputRate?.unit === "1M tokens")
    .map((m) => [m.id, [Number(m.inputRate.amount), Number(m.outputRate.amount), m.context || 0]]),
);
fs.writeFileSync(
  "server/model-prices.ts",
  `// Generated by scripts/build-app-models.mjs from the ${updatedAt} model snapshot. [input, output] are\n// USD per 1M tokens (micro-USD per token), markup included; the third value is the context window.\nexport const PRICES_AS_OF = "${updatedAt}";\nexport const modelPrices: Record<string, [number, number, number]> = ${JSON.stringify(charged)};\n`,
);
console.log(`${Object.keys(charged).length} chargeable text models`);
console.log(`${out.length} models, ${(fs.statSync("src/model-catalog.json").size / 1024).toFixed(0)} KB`);
