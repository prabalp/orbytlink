// Refresh with: node scripts/build-researched-catalog.mjs, then node --import tsx scripts/build-app-catalog-more.mjs
// Turns docs/mcp-research.json (one record per researched app, with the vendor page read and a live probe)
// into src/catalog-researched.ts. Only "verified" records whose probe answered become catalog entries;
// the rest stay listed as coming soon, with the reason kept in the research file.
import fs from "node:fs";
const research = JSON.parse(fs.readFileSync("docs/mcp-research.json", "utf8"));
const read = (f) => { const w = {}; new Function("window", fs.readFileSync(f, "utf8"))(w); return w; };
const { orbytLogos } = read("landing/catalog-logos.js");
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const presets = [], logos = {};
for (const r of research) {
  if (r.status !== "verified" || !r.live) continue;
  const id = slug(r.name);
  const p = { id, name: r.displayName || r.name, segment: r.segment, description: r.description, endpoint: r.endpoint, auth: r.auth };
  if (r.auth === "api-key") p.authHeader = r.authHeader;
  if (r.auth === "oauth") p.oauth = { mode: "discover" };
  if (r.ownClient) p.ownClient = true;
  p.notes = r.notes;
  p.docs = r.docs;
  presets.push(p);
  // Logos: a file in src/logos/ (copied by build-app-catalog-more) or an inline Simple Icons path.
  const logo = orbytLogos[r.name];
  if (logo?.path) logos[id] = { path: logo.path, hex: logo.hex };
}
fs.writeFileSync("src/catalog-researched.ts", `// Generated by scripts/build-researched-catalog.mjs from docs/mcp-research.json. Each entry is the
// vendor's own hosted MCP server, checked against the vendor's docs and probed live; edit the research
// file, not this one.
import type { Preset } from "./catalog";
export const researchedPresets: Preset[] = ${JSON.stringify(presets, null, 1)};
export const researchedLogos: Record<string, { path: string; hex: string }> = ${JSON.stringify(logos)};
`);
console.log(`${presets.length} researched connections`);
