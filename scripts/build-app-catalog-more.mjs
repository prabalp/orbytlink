// Refresh with: node --import tsx scripts/build-app-catalog-more.mjs (after build-landing-catalog.mjs)
// Writes src/catalog-more.ts: landing-page apps that are not connectable presets yet, plus their logo files.
import fs from "node:fs";
import path from "node:path";
import { catalog } from "../src/catalog.ts";
const read = (f) => { const w = {}; new Function("window", fs.readFileSync(f, "utf8"))(w); return w; };
const { orbytCatalog } = read("landing/catalog-data.js");
const { orbytLogos } = read("landing/catalog-logos.js");
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const presets = catalog.flatMap((p) => [p.id, slug(p.name)]);
// Same app under another name in the research list, or a duplicate of a preset.
const duplicates = new Set(["apollo", "exa-search", "firecrawl-scrape-url", "cloudflare-api-key", "twitter", "google-maps-geocoding"]);
fs.mkdirSync("src/logos", { recursive: true });
const apps = [];
for (const tool of orbytCatalog.tools) {
  const id = slug(tool.name);
  const logo = orbytLogos[tool.name];
  // Logo files are copied for every app, so one that becomes connectable keeps its mark.
  if (logo?.src && !logo?.path) fs.copyFileSync(path.join("landing", logo.src), `src/logos/${id.replace(/-/g, "_")}${path.extname(logo.src)}`);
  if (presets.includes(id) || duplicates.has(id)) continue;
  const app = { id, name: tool.name, segment: tool.category };
  if (logo?.path) app.logo = { path: logo.path, hex: logo.hex };
  apps.push(app);
}
fs.writeFileSync("src/catalog-more.ts", `// Generated by scripts/build-app-catalog-more.mjs. Apps on the landing page that cannot be connected yet:
// they come from our API research and have no vendor-verified MCP endpoint. Move one into catalog.ts
// (checked against the vendor's docs) to make it connectable.
export type ListedApp = { id: string; name: string; segment: string; logo?: { path: string; hex: string } };
export const moreApps: ListedApp[] = ${JSON.stringify(apps, null, 1)};
`);
console.log(`${apps.length} apps listed`);
